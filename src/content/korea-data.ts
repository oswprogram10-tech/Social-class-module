export function totalPop(yearIdx: number): number {
  return PROVINCES.reduce((s, p) => s + p.pop[yearIdx], 0);
}

export function capitalShare(yearIdx: number): number {
  const cap = PROVINCES.filter((p) => p.capital).reduce((s, p) => s + p.pop[yearIdx], 0);
  return cap / totalPop(yearIdx);
}

export function fmtPop(n: number): string {
  return n >= 10000 ? `${(n / 10000).toLocaleString('ko-KR', { maximumFractionDigits: 0 })}만 명` : `${n.toLocaleString('ko-KR')}명`;
}
